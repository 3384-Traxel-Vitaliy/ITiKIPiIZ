EXAMPLES = [
    "Маленькие студенты внимательно изучали новый русский учебник, который вчера принесла преподавательница.",

    "Неизвестный квакумп неожиданно появился рядом с большой машынай, после чего студенды быстро побежали домой.",

    "Вчера несколько опытных исследователей обсуждали результаты нового эксперимента с коллегами из московского университета.",

    "Я хотел рассказать им об этом странном происшествии, но они уже знали, что произошло возле старого дома.",

    "Квакумп лежал на деревянном столе, а маленький шушунчик неожиданно прыгнул рядом.",

    "Калушаточки, бутявок не трямкают, бутявки дюбые и зюмо-зюмо некузявые.",

    "Когда маленький квакумп внезапно вздрякнулся, старый шушунчик испугался, но бутявка быстро усяпала в лес.",
]


def test_examples(analyzer):
    # Выводим заголовок блока тестирования
    print("\n" + "=" * 70)
    print("ТЕСТОВЫЕ ПРЕДЛОЖЕНИЯ")
    print("=" * 70)

    # Проверяем каждое тестовое предложение
    for i, text in enumerate(EXAMPLES, 1):
        print(f"\n--- ПРЕДЛОЖЕНИЕ {i} ---")
        print(text)

        # Анализируем все слова в предложении
        results = analyzer.analyze_text(text)

        # Выводим результат анализа каждого слова
        for result in results:
            if isinstance(result, tuple):
                if len(result) >= 3:
                    word, lemma, pos = result[:3]
                    print(f"{word:20} -> лемма: {lemma:20} POS: {pos}")
            elif isinstance(result, dict):
                print(
                    f"{result.get('word', ''):20} -> "
                    f"лемма: {result.get('lemma', ''):20} "
                    f"POS: {result.get('pos', '')}"
                )


def run_tests(analyzer):
    # Запускаем набор тестовых предложений
    test_examples(analyzer)